#!/bin/sh
# Phase 0 spike: Raven's Vulkan GLSL -> SPIR-V (glslang) -> GLSL ES 3.00 / GLSL 4.10 (SPIRV-Cross).
# This is the same translation sokol-shdc performs internally; here the shader sources of
# src/render/vulkan/shaders are used unmodified, which is what the spike wants to prove.
set -e
SRC=../../src/render/vulkan/shaders
OUT=shaders
mkdir -p $OUT
for s in ui.vert ui.frag; do
  glslangValidator -V $SRC/$s -o $OUT/$s.spv >/dev/null
  # flat uniform arrays (no UBO) so GL 4.1 / GLES3 / WebGL2 can bind them by name
  spirv-cross $OUT/$s.spv --version 300 --es --flatten-ubo --glsl-emit-push-constant-as-ubo --output $OUT/$s.es300.glsl
  spirv-cross $OUT/$s.spv --version 410 --flatten-ubo --glsl-emit-push-constant-as-ubo --output $OUT/$s.gl410.glsl
done

# embed the generated GLSL as C strings (one header, ES 3.00 variants)
python3 - <<'PY'
import os
out = ["/* generated by gen_shaders.sh: do not edit */\n"]
for name, var in (("ui.vert", "spk_ui_vert"), ("ui.frag", "spk_ui_frag")):
    for target in ("es300", "gl410"):
        text = open(f"shaders/{name}.{target}.glsl").read()
        lit = "".join('"%s\\n"\n' % line.replace('\\', '\\\\').replace('"', '\\"') for line in text.splitlines())
        out.append(f"static const char {var}_{target}[] =\n{lit};\n")
open("shaders/shader_sources.h", "w").write("\n".join(out))
PY
