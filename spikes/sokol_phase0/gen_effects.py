#!/usr/bin/env python3
"""Phase 0: translate Raven effect shaders (SPIR-V, written with raven_effect.glsl) to GLSL ES 3.00
with SPIRV-Cross, and embed them keyed by a hash of their SPIR-V. This emulates what the planned
.rfx bundle (plan section 3.2) would hold for the GLES3 target: a backend that receives SPIR-V at
run time cannot translate it, so it looks the precompiled variant up.

GLES 3.0 / WebGL2 link vertex outputs to fragment inputs *by name*, so the fragment inputs are
renamed (by location) to the names of ui.vert's outputs."""
import os, re, struct, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
GEN = os.path.join(ROOT, "src/render/vulkan/generated")
OUT = os.path.join(os.path.dirname(__file__), "shaders")
NAMES = ["v_uv", "v_rect", "v_clip", "v_radii", "v_color", "v_border_color", "v_border_width", "v_flags", "v_params", "v_inv_size", "v_pointer"]

def fnv(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

def builtin(name):
    text = open(os.path.join(GEN, f"effect_{name}_spv.h")).read()
    words = [int(w, 16) for w in re.findall(r"0x[0-9a-fA-F]{8}", text)]
    return struct.pack("<%dI" % len(words), *words)

effects = {n: builtin(n) for n in ("aurora", "shimmer", "neon", "ripple", "plasma", "grain", "spotlight", "mesh")}
for n in ("wave", "liquid"):
    effects[n] = open(os.path.join(ROOT, "examples/effects", n + ".spv"), "rb").read()

entries = []
for name, spv in effects.items():
    path = os.path.join(OUT, f"fx_{name}.spv")
    open(path, "wb").write(spv)
    cmd = ["spirv-cross", path, "--version", "300", "--es"]
    for loc, n in enumerate(NAMES):
        cmd += ["--rename-interface-variable", "in", str(loc), n]
    glsl = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    open(os.path.join(OUT, f"fx_{name}.es300.glsl"), "w").write(glsl)
    entries.append((name, fnv(spv), glsl))

lines = ["/* generated by gen_effects.py: do not edit */\n"]
for name, h, glsl in entries:
    lit = "".join('"%s\\n"\n' % l.replace("\\", "\\\\").replace('"', '\\"') for l in glsl.splitlines())
    lines.append(f"static const char spk_fx_{name}[] =\n{lit};\n")
lines.append("static const struct { const char* name; uint64_t hash; const char* glsl; } spk_fx_table[] = {")
for name, h, _ in entries:
    lines.append(f'\t{{ "{name}", 0x{h:016x}ull, spk_fx_{name} }},')
lines.append("};\n")
open(os.path.join(OUT, "effect_sources.h"), "w").write("\n".join(lines))
print("effects:", ", ".join(effects))
