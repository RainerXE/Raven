#!/usr/bin/env python3
"""Turns a binary file into a C source defining a byte array.

    python3 tools/embed.py <input> <symbol> <output.c> ["comment"]

Defines:
    const unsigned char <symbol>_data[];
    const size_t <symbol>_size;
"""
import sys

def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    source, symbol, target = sys.argv[1:4]
    comment = sys.argv[4] if len(sys.argv) > 4 else source
    data = open(source, "rb").read()
    lines = []
    for offset in range(0, len(data), 20):
        lines.append("\t" + ",".join(str(byte) for byte in data[offset:offset + 20]) + ",")
    with open(target, "w") as out:
        out.write("/**\n * Generated by tools/embed.py - do not edit.\n * %s\n */\n\n" % comment)
        out.write("#include <stddef.h>\n\n")
        out.write("const unsigned char %s_data[] = {\n%s\n};\n\n" % (symbol, "\n".join(lines)))
        out.write("const size_t %s_size = %d;\n" % (symbol, len(data)))

if __name__ == "__main__":
    main()
