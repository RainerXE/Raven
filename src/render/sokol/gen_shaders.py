#!/usr/bin/env python3
"""Generates the shader sources of the Sokol backend from the Vulkan GLSL of src/render/vulkan/shaders.

    glslangValidator -> SPIR-V -> spirv-cross -> GLSL ES 3.00   (GLES3 / WebGL2)

Run it when a shader changes (needs glslang and spirv-cross; the outputs are committed, like the
SPIR-V headers of the Vulkan backend). More targets (MSL, HLSL, GLSL 4.10) are added to TARGETS.

 - ui.vert / ui.frag are used unmodified.
 - blur.frag keeps a vec2 and an int in its push constants; SPIRV-Cross cannot flatten that for GL,
   so they are packed into one vec4 (xy = step, z = mode) in a patched copy.
 - Effects (raven_effect.glsl) are translated from the SPIR-V embedded in the Vulkan backend. GLES 3.0
   and WebGL2 link varyings by name, so the fragment inputs are renamed, by location, to the names of
   the ui.vert outputs. Each built-in is keyed by a hash of its SPIR-V (what CreateShader receives).
"""
import os, re, struct, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
VK = os.path.join(ROOT, "src", "render", "vulkan")
OUT = os.path.join(HERE, "generated")
TARGETS = {"es300": ["--version", "300", "--es"]}
FLATTEN = ["--flatten-ubo", "--glsl-emit-push-constant-as-ubo"]
VARYINGS = ["v_uv", "v_rect", "v_clip", "v_radii", "v_color", "v_border_color", "v_border_width", "v_flags", "v_params", "v_inv_size", "v_pointer"]
EFFECTS = ["aurora", "shimmer", "neon", "ripple", "plasma", "grain", "spotlight", "mesh"]

def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout

def fnv(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

def c_string(name, text):
    lit = "".join('\t"%s\\n"\n' % l.replace("\\", "\\\\").replace('"', '\\"') for l in text.splitlines())
    return f"static const char {name}[] =\n{lit};\n"

def cross(spv, target, extra=()):
    return run("spirv-cross", spv, *TARGETS[target], *extra)

def main():
    os.makedirs(OUT, exist_ok=True)
    tmp = tempfile.mkdtemp()
    shaders = ["/* generated by gen_shaders.py: do not edit */\n"]
    for target in TARGETS:
        parts = {}
        for name, src in (("ui_vert", "ui.vert"), ("ui_frag", "ui.frag"), ("blur_vert", "blur.vert"), ("blur_frag", "blur.frag")):
            path = os.path.join(VK, "shaders", src)
            if name == "blur_frag":
                text = open(path).read()
                text = text.replace("vec2 step;", "vec4 p;").replace("int mode;", "")
                text = text.replace("pc.step", "pc.p.xy").replace("pc.mode", "int(pc.p.z + 0.5)")
                path = os.path.join(tmp, "blur.frag")
                open(path, "w").write(text)
            spv = os.path.join(tmp, name + ".spv")
            run("glslangValidator", "-V", path, "-o", spv)
            parts[name] = cross(spv, target, FLATTEN)
            shaders.append(c_string(f"rvn_sg_{name}_{target}", parts[name]))
    open(os.path.join(OUT, "sg_shaders.h"), "w").write("\n".join(shaders))

    fx = ["/* generated by gen_shaders.py: do not edit */\n"]
    table = []
    for name in EFFECTS:
        text = open(os.path.join(VK, "generated", f"effect_{name}_spv.h")).read()
        words = [int(w, 16) for w in re.findall(r"0x[0-9a-fA-F]{8}", text)]
        data = struct.pack("<%dI" % len(words), *words)
        spv = os.path.join(tmp, f"fx_{name}.spv")
        open(spv, "wb").write(data)
        rename = []
        for loc, n in enumerate(VARYINGS):
            rename += ["--rename-interface-variable", "in", str(loc), n]
        for target in TARGETS:
            fx.append(c_string(f"rvn_sg_fx_{name}_{target}", cross(spv, target, rename)))
        table.append((name, fnv(data)))
    fx.append("/* hash (FNV-1a 64) of the SPIR-V of each built-in effect, and its GLSL ES 3.00 variant */")
    fx.append("static const struct { const char* name; uint64_t hash; const char* es300; } rvn_sg_effects[] = {")
    for name, h in table:
        fx.append(f'\t{{ "{name}", 0x{h:016x}ull, rvn_sg_fx_{name}_es300 }},')
    fx.append("};\n")
    open(os.path.join(OUT, "sg_effects.h"), "w").write("\n".join(fx))
    print("wrote", os.path.join(OUT, "sg_shaders.h"), "and sg_effects.h")

main()
